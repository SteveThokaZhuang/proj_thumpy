"""Q3 预登记: B 组里该不该出现「负号」—— 纯计算, 0 GPU, 0 读盘。

## 为什么这是个直击主旨的问题

§7.2 的 A 组 (7 个 seed) 里, **只有 seed 55555 的 ΔF1 = −0.0345 是负的**。
它是符号检验被打掉的主因 (两尾最小 p = 2/2^7 = 0.0156 要求 7/7 同向),
也是 SD 从 ~0.02 抬到 0.0309 的主要贡献者。

那么问题来了: 55555 的负号到底是什么?

  (H-初值) 那个 LoRA 初值特别差 ⇒ 负号**属于初始化**, 是种子的事;
  (H-顺序) 数据顺序换一换就能翻号 ⇒ 负号**属于 shuffle**,
           是这个效应本身在噪声下不稳。

**B 组正好能判**: 它固定 seed=42 (初值逐位相同), 只变 data_seed。
所以 B 组里出现的任何一个负号, **按构造只能来自数据顺序**。

## 预登记 (2026-09-18 00:0x, 结果到货**之前**写下)

用 A 组的观测均值 + B 组的待测 SD 当模型, 算 B 组 7 个 run 里出现
至少一个负号的概率。**注意这是"若效应为真的零模型"下的预期, 不是预测效应为真。**

  P(单次为负) = Φ(−mean / SD_B)
  P(7 次里 >=1 个负) = 1 − (1 − p)^7

## 判读表 (先写死, 免得事后挑说法)

| B 组负号数 | 读法 |
|---|---|
| 0 | 与「效应稳定、55555 是初值特例」一致 |
| 1 | 与模型预期一致, **不加也不减**——但足以说明负号不必来自初值 |
| >=2 | 数据顺序**单独**就能反复翻号 ⇒ +0.034 这个效应在 nuisance 变量下不稳, 必须在正文里说 |

⚠️ 无论哪一档, **B 组都只能说明"散在哪", 不能用来论证"效应非零"**
(§7.4b 已预登记的判据)。这条不能因为 B 组出现负号就反过来用。

用法:
  python scripts/g1_q3_prereg.py                 # 用默认 (A 组实测均值)
  python scripts/g1_q3_prereg.py --sd-b 0.0309   # 指定假想的 B 组 SD
"""
import argparse
from math import erf, sqrt

A_MEAN = 0.0340        # §7.2: A 组 7 个 seed 的 ΔF1 均值 (实测)
A_SD = 0.0309          # §7.2: A 组 SD (实测)
A_NEG = 1              # §7.2: A 组里负号个数 (seed 55555)


def phi(x):
    """标准正态 CDF, 只用标准库 (不引入 scipy 依赖)。"""
    return 0.5 * (1.0 + erf(x / sqrt(2.0)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sd-b", type=float, default=None,
                    help="假想的 B 组 SD; 默认在 0 到 A_SD 之间扫一遍")
    args = ap.parse_args()

    print("=" * 74)
    print("  Q3 预登记: B 组 (固定 seed=42, 只变 data_seed) 该不该出现负号")
    print("=" * 74)
    print(f"\n  取自 A 组实测 (§7.2): 均值 = {A_MEAN:+.4f}, SD = {A_SD:.4f}, "
          f"负号 {A_NEG}/7")

    print(f"\n  模型: B 组的 ΔF1 ~ 均值 {A_MEAN:+.4f}, 标准差 SD_B")
    print(f"  按构造 B 组的初值逐位相同 ⇒ 负号只能来自**数据顺序**。\n")
    print(f"  {'SD_B':>8}{'P(单次为负)':>14}{'P(>=1个负号/7)':>18}{'期望负号数':>12}")
    sds = [args.sd_b] if args.sd_b else [0.010, 0.015, 0.020, 0.025, A_SD]
    for sd in sds:
        p = phi(-A_MEAN / sd)
        p_at_least_one = 1.0 - (1.0 - p) ** 7
        print(f"  {sd:>8.4f}{p:>14.3f}{p_at_least_one:>18.3f}{7 * p:>12.2f}")

    sd = args.sd_b if args.sd_b else A_SD
    p = phi(-A_MEAN / sd)
    print(f"\n  ── 以 SD_B = {sd:.4f} 为主判据 ──")
    print(f"     单次为负的概率 p = {p:.3f}; 期望负号数 = 7p = {7*p:.2f}")

    # ---- 零模型下的负号数分布 (二项 n=7) ----
    # 🔴 2026-09-18 00:1x 自我更正: 本脚本第一版把判读表写成
    #    「>=2 个负号 ⇒ 数据顺序能反复翻号」。**那条阈值定得太松了** ——
    #    它看着"严", 实际在零模型下一点都不罕见。算出来 P(>=2) = 0.246,
    #    也就是说**即使效应完全稳定, 也有 1/4 的概率看到 >=2 个负号**,
    #    拿它当证据就是 25% 的假发现率。
    #    这与 Q4 那次误报是**同一个病根**: 定阈值前没先算零分布。
    #    (那次是定得太严 -> 假警报; 这次是定得太松 -> 假发现。)
    #    现在把完整分布算出来, 阈值直接由尾概率定。
    from math import comb
    dist = [comb(7, k) * p**k * (1 - p)**(7 - k) for k in range(8)]
    print(f"\n  ── 零模型下负号数的分布 (二项 n=7, p={p:.3f}) ──")
    print(f"     {'负号数':>6}{'概率':>10}{'累积 >= k':>14}")
    for k in range(8):
        tail = sum(dist[k:])
        print(f"     {k:>6}{dist[k]:>10.3f}{tail:>14.3f}")

    print(f"\n  ── 判读表 (2026-09-18 00:1x 定稿, 阈值由上面的尾概率定) ──")
    print(f"     先看 B 组的**实测 SD_B**, 再对照本表。以 SD_B≈{A_SD:.4f} (最坏情形)")
    print(f"     为例: 期望 {7*p:.2f} 个负号, P(>=2)={sum(dist[2:]):.3f}, "
          f"P(>=3)={sum(dist[3:]):.3f}")
    print(f"     · 0~1 个负号 : 与零模型相符, **不加不减**")
    print(f"                    (但 1 个已足以说明「负号不必来自初值」)")
    print(f"     · 2 个负号   : 零模型下 {sum(dist[2:]):.0%} 会发生 —— **不构成证据**, 别当发现报")
    print(f"     · >=3 个负号 : 零模型下仅 {sum(dist[3:]):.1%} ⇒ 这时才谈得上")
    print(f"                    「数据顺序单独就能翻号」, 正文必须写")

    print(f"\n  ⚠️ **n=7 的符号计数是很粗的仪器**: 即便效应完全稳定, 看到 >=2 个")
    print(f"     负号也有 {sum(dist[2:]):.0%} 的概率。所以本表主要用途是**防我自己过度解读**,")
    print(f"     而不是提供一条灵敏的检验。真要判稳定性, 得看 SD_B 与逐点值,")
    print(f"     不能只看负号个数。")
    print(f"\n  ⚠️ 无论哪一档: B 组只说明「散在哪」, **不能**用来论证「效应非零」。")
    print(f"     这条是 §7.4b 已预登记的判据, 不因 B 组出现负号而反转。")


if __name__ == "__main__":
    main()
